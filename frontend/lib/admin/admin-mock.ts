// 대시보드 요약 — 화면이 직접 세지 않고 이 순수 집계를 그리기만 한다(운영자 콘솔과 같은 규율).
export function buildAdminDashboard(
  eventId: string,
  organizations: AdminOrganization[] = MOCK_ORGANIZATIONS,
  meetings: AdminMeeting[] = MOCK_MEETINGS,
  notifications: AdminNotificationLog[] = MOCK_NOTIFICATION_LOGS,
  activity: (AdminActivity & { event_id: string })[] = MOCK_ACTIVITY,
): AdminDashboard {
  const orgs = scopeToEvent(organizations, eventId)
  const mtgs = scopeToEvent(meetings, eventId)
  const ntfs = scopeToEvent(notifications, eventId)
  return {
    event_id: eventId,
    org_total: orgs.length,
    exhibitor_count: orgs.filter((o) => o.role === "exhibitor").length,
    buyer_count: orgs.filter((o) => o.role === "buyer").length,
    unsubmitted_count: countUnsubmitted(orgs),
    meeting_total: mtgs.length,
    meeting_scheduled: mtgs.filter((m) => m.status === "scheduled").length,
    notification_sent: ntfs.length,
    recent_activity: scopeToEvent(activity, eventId)
      .slice()
      .sort((a, b) => b.at.localeCompare(a.at))
      .slice(0, 5)
      .map(({ id, at, actor, summary }) => ({ id, at, actor, summary })),
  }
}
